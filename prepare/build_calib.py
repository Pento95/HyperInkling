"""Build the calibration (and a held-out evaluation) corpus from public datasets.

Prompts come from the datasets; the answers (reasoning, content, tool calls)
are generated by the reference checkpoint served at URL, so the corpus is the
text the model itself produces. Each record is a complete chat transcript,
ready to be rendered by the model's chat template:

    {"source": ..., "messages": [...], "tools": [...] | null, "effort": ...}

where the last message is the generated assistant turn. Wikipedia passages
also enter raw (teacher-forced as a user message, no generation).

Sources (data/calib-src, one file each; see README for licenses):
    docvqa     pixparse/docvqa-single-page-questions   page image + question
    hermes     NousResearch/hermes-function-calling-v1 tools, tool results
    magicoder  ise-uiuc/Magicoder-Evol-Instruct-110K   code
    wiki       wikimedia/wikipedia 20231101.it          Italian tasks + raw
    ultrachat  HuggingFaceH4/ultrachat_200k             general chat

    venv/bin/python prepare/build_calib.py data/calib/calib.jsonl data/calib/eval.jsonl
"""

import base64
import json
import os
import random
import re
import sys
import threading
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor

import pyarrow.parquet as pq

URL = "http://127.0.0.1:18030/v1/chat/completions"
MODEL = "inkling-2-mini"
SRC = "data/calib-src/"
# HYPERINKLING_CALIB_SEED draws a further, disjoint-by-content calibration set.
SEED = int(os.environ.get("HYPERINKLING_CALIB_SEED", "20261121"))
# Records per source: (calibration, evaluation).
# A best-effort calibration: a small slice of each source.
COUNTS = {
    "docvqa": (12, 4),
    "hermes_single": (12, 4),
    "hermes_multi": (12, 4),
    "magicoder": (14, 4),
    "wiki_task": (14, 4),
    "wiki_raw": (8, 0),
    "ultrachat": (10, 3),
}
EFFORTS = ("low", "medium", None)  # None: the template's default (0.9)
MAX_TOKENS = 3072

WIKI_TASKS = [
    "Riassumi il testo seguente in italiano, in 5-8 frasi.",
    "Estrai dal testo seguente, in JSON, le persone, i luoghi e le date citate.",
    "Scrivi tre domande con risposta, in italiano, sul testo seguente.",
    "Spiega il testo seguente a uno studente delle superiori, in italiano.",
    "Elenca in punti i fatti principali del testo seguente.",
]
TOOLS_RE = re.compile(r"<tools>\n(.*?)\n</tools>", re.S)
CALL_RE = re.compile(r"<tool_call>\s*(\{.*?\})\s*</tool_call>", re.S)
RESP_RE = re.compile(r"<tool_response>\s*(\{.*?\})\s*</tool_response>", re.S)


def _hermes_tools(conv):
    """The tool list of a Hermes system prompt, or None when it is not JSON."""
    try:
        return json.loads(TOOLS_RE.search(conv[0]["value"]).group(1))
    except (AttributeError, json.JSONDecodeError):
        return None


def docvqa(rng, n):
    t = pq.read_table(SRC + "docvqa/data/train-00002-of-00036.parquet")
    rows = rng.sample(range(t.num_rows), n)
    out = []
    for i in rows:
        r = t.slice(i, 1).to_pylist()[0]
        url = "data:image/png;base64," + base64.b64encode(r["image"]["bytes"]).decode()
        out.append({"messages": [{"role": "user", "content": [
            {"type": "image_url", "image_url": {"url": url}},
            {"type": "text", "text": r["question"]}]}], "tools": None})
    return out


def hermes_single(rng, n):
    ex = json.load(open(SRC + "hermes-fc/func-calling-singleturn.json"))
    out = []
    for e in rng.sample(ex, n * 2):
        conv = e["conversations"]
        tools = _hermes_tools(conv)
        if tools is None:
            continue
        user = next(c["value"] for c in conv if c["from"] == "human")
        out.append({"messages": [{"role": "user", "content": user}], "tools": tools})
        if len(out) == n:
            break
    return out


def hermes_multi(rng, n):
    """The dataset's calls and tool results; the model writes the final answer."""
    ex = [e for e in json.load(open(SRC + "hermes-fc/func-calling.json"))
          if [c["from"] for c in e["conversations"]] == ["system", "human", "gpt", "tool", "gpt"]]
    out = []
    for e in rng.sample(ex, n * 2):
        conv = e["conversations"]
        try:
            calls = [json.loads(c) for c in CALL_RE.findall(conv[2]["value"])]
            resps = [json.loads(r) for r in RESP_RE.findall(conv[3]["value"])]
        except json.JSONDecodeError:
            continue
        tools = _hermes_tools(conv)
        if not calls or len(calls) != len(resps) or tools is None:
            continue
        tool_calls = [{"id": f"call_{i}", "type": "function", "function": {
            "name": c["name"], "arguments": json.dumps(c.get("arguments", {}))}}
            for i, c in enumerate(calls)]
        msgs = [{"role": "user", "content": conv[1]["value"]},
                {"role": "assistant", "content": "", "tool_calls": tool_calls}]
        for i, r in enumerate(resps):
            msgs.append({"role": "tool", "tool_call_id": f"call_{i}",
                         "content": json.dumps(r.get("content", r))})
        out.append({"messages": msgs, "tools": tools})
        if len(out) == n:
            break
    return out


def magicoder(rng, n):
    lines = open(SRC + "magicoder/data-evol_instruct-decontaminated.jsonl").readlines()
    return [{"messages": [{"role": "user", "content": json.loads(line)["instruction"]}],
             "tools": None} for line in rng.sample(lines, n)]


def _wiki_passages(rng, n):
    t = pq.read_table(SRC + "wiki-it/20231101.it/train-00002-of-00010.parquet",
                      columns=["title", "text"])
    out = []
    while len(out) < n:
        r = t.slice(rng.randrange(t.num_rows), 1).to_pylist()[0]
        text = r["text"].strip()
        if len(text) < 2500:
            continue
        out.append(f"{r['title']}\n\n{text[:6000]}")
    return out


def wiki_task(rng, n):
    return [{"messages": [{"role": "user", "content": f"{rng.choice(WIKI_TASKS)}\n\n{p}"}],
             "tools": None} for p in _wiki_passages(rng, n)]


def wiki_raw(rng, n):
    # Teacher-forced as is: a user message, then no generation.
    return [{"messages": [{"role": "user", "content": p}], "tools": None, "raw": True}
            for p in _wiki_passages(rng, n)]


def ultrachat(rng, n):
    t = pq.read_table(SRC + "ultrachat/data/test_gen-00000-of-00001-3d4cd8309148a71f.parquet",
                      columns=["prompt"])
    return [{"messages": [{"role": "user", "content": t.slice(i, 1).to_pylist()[0]["prompt"]}],
             "tools": None} for i in rng.sample(range(t.num_rows), n)]


def generate(rec, rng_effort, lock, stats):
    if rec.get("raw"):
        return rec
    body = {"model": MODEL, "messages": rec["messages"], "max_tokens": MAX_TOKENS,
            "temperature": 0.7, "top_p": 0.95, "seed": SEED}
    if rec["tools"]:
        body["tools"] = rec["tools"]
    if rng_effort is not None:
        body["reasoning_effort"] = rng_effort
    req = urllib.request.Request(URL, json.dumps(body).encode(),
                                 {"Content-Type": "application/json"})
    try:
        r = json.load(urllib.request.urlopen(req, timeout=3600))
    except urllib.error.HTTPError as e:  # e.g. a prompt longer than the context
        print(f"\nskipped {rec['source']}: HTTP {e.code} {e.read()[:200]!r}")
        return None
    m = r["choices"][0]["message"]
    turn = {"role": "assistant", "content": m.get("content") or ""}
    reasoning = m.get("reasoning") or m.get("reasoning_content")
    if reasoning:
        turn["reasoning_content"] = reasoning
    if m.get("tool_calls"):
        turn["tool_calls"] = [{"id": tc["id"], "type": "function", "function": tc["function"]}
                              for tc in m["tool_calls"]]
    rec["messages"] = rec["messages"] + [turn]
    rec["effort"] = rng_effort
    rec["finish_reason"] = r["choices"][0]["finish_reason"]
    with lock:
        stats["tokens"] += r["usage"]["total_tokens"]
        stats["done"] += 1
        print(f"\r{stats['done']} records, {stats['tokens']} tokens", end="", flush=True)
    return rec


def main(calib_path, eval_path):
    rng = random.Random(SEED)
    calib, evals = [], []
    for name, (nc, ne) in COUNTS.items():
        recs = globals()[name](rng, nc + ne)
        for r in recs:
            r["source"] = name
        calib += recs[:nc]
        evals += recs[nc:]
    if os.path.exists(eval_path):
        # Keep the existing evaluation set out of a new calibration set.
        held = {json.dumps(json.loads(line)["messages"][0]["content"]) for line in open(eval_path)}
        before = len(calib)
        calib = [r for r in calib if json.dumps(r["messages"][0]["content"]) not in held]
        print(f"{before - len(calib)} calibration records overlapped the eval set, dropped")
    lock, stats = threading.Lock(), {"tokens": 0, "done": 0}
    for path, recs in ((calib_path, calib), (eval_path, evals)):
        if os.path.exists(path):
            print(f"{path} exists, kept")
            continue
        efforts = [rng.choice(EFFORTS) for _ in recs]
        with ThreadPoolExecutor(6) as ex:
            done = list(ex.map(lambda a: generate(*a, lock, stats), zip(recs, efforts)))
        done = [r for r in done if r is not None]
        with open(path, "w") as f:
            for r in done:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
        print(f"\n{len(done)} records -> {path}")


if __name__ == "__main__":
    main(*sys.argv[1:])
